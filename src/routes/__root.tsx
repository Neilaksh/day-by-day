function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // Apply saved theme preference on mount so it persists across all routes and page refreshes
  useEffect(() => {
    const isDark =
      localStorage.getItem("theme") === "dark" ||
      (!("theme" in localStorage) && window.matchMedia("(prefers-color-scheme: dark)").matches);
    if (isDark) {
      document.documentElement.classList.add("dark");
    } else {
      document.documentElement.classList.remove("dark");
    }
  }, []);

  useEffect(() => {
    // Remove Lovable badge if present (CSS in styles.css also handles this;
    // this is a one-time DOM cleanup, not continuous observation).
    const removeBadge = () => {
      const candidates = document.querySelectorAll(
        "#lovable-badge, [id*='lovable-badge'], [class*='lovable-badge'], [data-lovable-badge], a[href*='lovable.dev']",
      );
      candidates.forEach((el) => {
        const container = el.closest("[id*='lovable'], div[style*='position: fixed']") || el;
        container.remove();
      });
    };

    removeBadge();

    // Register Service Worker for PWA (Firefox Android, Chrome, Safari)
    if (typeof window !== "undefined" && "serviceWorker" in navigator) {
      const registerServiceWorker = () => {
        navigator.serviceWorker
          .register("/sw.js", { scope: "/" })
          .catch((err) => {
            console.error("Service Worker registration error:", err);
          });
      };

      if (document.readyState === "complete") {
        registerServiceWorker();
      } else {
        window.addEventListener("load", registerServiceWorker, { once: true });
      }
    }
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster />
      <CookieNotice />
    </QueryClientProvider>
  );
}
